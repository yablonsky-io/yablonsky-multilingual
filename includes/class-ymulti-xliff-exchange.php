<?php
namespace Yablonsky\Multilingual;

if (!defined('ABSPATH')) exit;

/** Secure XLIFF 1.2/2.0 interchange for durable translation jobs. */
final class XLIFFExchange {
  private const NS_META = 'https://yablonsky.io/ymulti/xliff';
  private const MAX_FILE_BYTES = 5242880;

  public static function init(): void {
    if (!is_admin()) return;
    add_action('admin_post_ymulti_xliff_export', [__CLASS__, 'handle_export']);
    add_action('admin_post_ymulti_xliff_import', [__CLASS__, 'handle_import']);
  }

  public static function available(): bool {
    return class_exists('DOMDocument') && class_exists('DOMXPath');
  }

  public static function export_url(int $job_id, string $format = '12'): string {
    $format = $format === '20' ? '20' : '12';
    return wp_nonce_url(
      add_query_arg(['action' => 'ymulti_xliff_export', 'job_id' => $job_id, 'format' => $format], admin_url('admin-post.php')),
      'ymulti_xliff_export_' . $job_id . '_' . $format
    );
  }

  public static function handle_export(): void {
    if (!self::available()) wp_die(esc_html__('XLIFF requires the PHP DOM extension on this server.', 'yablonsky-multilingual'));
    $job_id = (int) filter_input(INPUT_GET, 'job_id', FILTER_VALIDATE_INT);
    $format_raw = filter_input(INPUT_GET, 'format', FILTER_UNSAFE_RAW);
    $format = is_string($format_raw) && $format_raw === '20' ? '20' : '12';
    check_admin_referer('ymulti_xliff_export_' . $job_id . '_' . $format);
    $job = TranslationJobs::get_job($job_id);
    if (!$job || !TranslationJobs::can_view_job($job)) wp_die(esc_html__('Forbidden', 'yablonsky-multilingual'));

    $xml = self::build_document($job, $format);
    if (is_wp_error($xml)) wp_die(esc_html($xml->get_error_message()));
    $hash = TranslationJobs::source_hash((int) $job['source_post_id']);
    TranslationJobs::update_job($job_id, ['source_hash' => $hash, 'exported_hash' => $hash, 'exported_at' => current_time('mysql', true)]);
    TranslationJobs::log_event($job_id, 'xliff_exported', sprintf(
      /* translators: %s: exported XLIFF format version. */
      __('XLIFF %s package exported.', 'yablonsky-multilingual'),
      $format === '20' ? '2.0' : '1.2'
    ), ['format' => $format, 'source_hash' => $hash]);

    $filename = 'ymulti-job-' . $job_id . '-' . sanitize_file_name((string) $job['source_locale']) . '-' . sanitize_file_name((string) $job['target_locale']) . ($format === '20' ? '-xliff2.xlf' : '-xliff12.xlf');
    nocache_headers();
    header('Content-Type: application/x-xliff+xml; charset=UTF-8');
    header('Content-Disposition: attachment; filename="' . $filename . '"');
    header('X-Content-Type-Options: nosniff');
    echo $xml; // phpcs:ignore WordPress.Security.EscapeOutput.OutputNotEscaped -- Generated XML download, not HTML.
    exit;
  }

  public static function handle_import(): void {
    if (!self::available()) self::redirect_notice('error', __('XLIFF requires the PHP DOM extension on this server.', 'yablonsky-multilingual'));
    if (!current_user_can(TranslationJobs::CAP_TRANSLATE) && !current_user_can(TranslationJobs::CAP_REVIEW) && !current_user_can(TranslationJobs::CAP_MANAGE)) wp_die(esc_html__('Forbidden', 'yablonsky-multilingual'));
    check_admin_referer('ymulti_xliff_import', 'ymulti_xliff_nonce');

    if (empty($_FILES['xliff_file']) || !is_array($_FILES['xliff_file'])) self::redirect_notice('error', __('Choose an XLIFF file to import.', 'yablonsky-multilingual'));
    $error = isset($_FILES['xliff_file']['error']) ? (int) $_FILES['xliff_file']['error'] : UPLOAD_ERR_NO_FILE;
    $size = isset($_FILES['xliff_file']['size']) ? (int) $_FILES['xliff_file']['size'] : 0;
    // tmp_name is generated by PHP, then constrained by is_uploaded_file() before any read.
    $tmp = isset($_FILES['xliff_file']['tmp_name']) ? sanitize_text_field(wp_unslash((string) $_FILES['xliff_file']['tmp_name'])) : '';
    $name = isset($_FILES['xliff_file']['name']) ? sanitize_file_name(wp_unslash((string) $_FILES['xliff_file']['name'])) : '';
    if ($error !== UPLOAD_ERR_OK || $tmp === '' || !is_uploaded_file($tmp)) self::redirect_notice('error', __('PHP rejected the XLIFF upload. Upload the file again within the server limits.', 'yablonsky-multilingual'));
    // The request's file-size field is not authoritative. Recheck the actual
    // uploaded temporary file before parsing, even when PHP reports success.
    $actual_size = @filesize($tmp);
    if ($size <= 0 || $size > self::MAX_FILE_BYTES || $actual_size === false || $actual_size <= 0 || $actual_size > self::MAX_FILE_BYTES) {
      self::redirect_notice('error', __('XLIFF files must be between 1 byte and 5 MB.', 'yablonsky-multilingual'));
    }
    $ext = strtolower(pathinfo($name, PATHINFO_EXTENSION));
    if (!in_array($ext, ['xlf', 'xliff', 'xml'], true)) self::redirect_notice('error', __('Only .xlf, .xliff or .xml interchange files are accepted.', 'yablonsky-multilingual'));

    if (function_exists('finfo_open')) {
      $finfo = finfo_open(FILEINFO_MIME_TYPE);
      $mime = $finfo ? (string) finfo_file($finfo, $tmp) : '';
      if ($finfo) finfo_close($finfo);
      $allowed = ['application/xml', 'text/xml', 'application/x-xliff+xml', 'text/plain', 'application/octet-stream'];
      if ($mime !== '' && !in_array($mime, $allowed, true)) self::redirect_notice('error', __('Choose a valid XML/XLIFF file for this import.', 'yablonsky-multilingual'));
    }

    $xml = file_get_contents($tmp, false, null, 0, self::MAX_FILE_BYTES + 1);
    if (!is_string($xml) || $xml === '') self::redirect_notice('error', __('The XLIFF file requires readable XML content.', 'yablonsky-multilingual'));
    if (stripos($xml, '<!DOCTYPE') !== false || stripos($xml, '<!ENTITY') !== false) self::redirect_notice('error', __('XLIFF imports accept standard XML and reject DOCTYPE or entity declarations.', 'yablonsky-multilingual'));

    $parsed = self::parse_document($xml);
    if (is_wp_error($parsed)) self::redirect_notice('error', $parsed->get_error_message());
    $job_id = absint($parsed['job_id'] ?? 0);
    $job = TranslationJobs::get_job($job_id);
    if (!$job || (!TranslationJobs::can_work_job($job) && !TranslationJobs::can_review_job($job))) self::redirect_notice('error', __('Translation-job import permission is required for this action.', 'yablonsky-multilingual'));

    $expected_hash = (string) ($parsed['source_hash'] ?? '');
    $current_hash = TranslationJobs::source_hash((int) $job['source_post_id']);
    if ($expected_hash === '' || $current_hash === '' || !hash_equals($expected_hash, $current_hash)) {
      self::redirect_notice('error', __('The source changed after this XLIFF package was created. Export a fresh package before importing to prevent stale translations from overwriting newer source content.', 'yablonsky-multilingual'));
    }
    if ((string) ($job['target_locale'] ?? '') !== (string) ($parsed['target_locale'] ?? '')) self::redirect_notice('error', __('Choose an XLIFF file whose target language matches this translation job.', 'yablonsky-multilingual'));

    $result = self::apply_import($job, $parsed);
    if (is_wp_error($result)) self::redirect_notice('error', $result->get_error_message());
    TranslationJobs::update_job($job_id, ['target_post_id' => (int) $result, 'status' => TranslationJobs::STATUS_REVIEW, 'source_hash' => $current_hash]);
    TranslationJobs::log_event($job_id, 'xliff_imported', sprintf(
      /* translators: %s: imported XLIFF format version. */
      __('XLIFF %s imported to review draft.', 'yablonsky-multilingual'),
      (string) ($parsed['version'] ?? '')
    ), ['version' => (string) ($parsed['version'] ?? ''), 'target_post_id' => (int) $result]);
    self::redirect_notice('success', sprintf(
      /* translators: %d: target WordPress draft ID updated from XLIFF. */
      __('XLIFF imported into review draft #%d. Publishing remains human-controlled.', 'yablonsky-multilingual'),
      (int) $result
    ));
  }

  /** @return string|\WP_Error */
  public static function build_document(array $job, string $format = '12') {
    if (!self::available()) return new \WP_Error('ymulti_xliff_dom', __('XLIFF requires the PHP DOM extension.', 'yablonsky-multilingual'));
    $source_id = absint($job['source_post_id'] ?? 0);
    $source = get_post($source_id);
    if (!$source instanceof \WP_Post) return new \WP_Error('ymulti_xliff_source', __('Choose an existing source post for this translation job.', 'yablonsky-multilingual'));
    $units = self::units_for_job($job);
    if (is_wp_error($units)) return $units;
    $hash = TranslationJobs::source_hash($source_id);
    $source_locale = (string) ($job['source_locale'] ?? RuntimeAuthority::effective_post_language($source_id));
    $target_locale = (string) ($job['target_locale'] ?? '');
    if ($format === '20') return self::build_20($job, $units, $hash, $source_locale, $target_locale);
    return self::build_12($job, $units, $hash, $source_locale, $target_locale);
  }

  /** @return array<int,array<string,string>>|\WP_Error */
  private static function units_for_job(array $job) {
    $source_id = absint($job['source_post_id'] ?? 0);
    $target_id = absint($job['target_post_id'] ?? 0);
    $source = get_post($source_id);
    if (!$source instanceof \WP_Post) return new \WP_Error('ymulti_xliff_source', __('Choose an existing source post for this translation job.', 'yablonsky-multilingual'));
    $target = $target_id > 0 ? get_post($target_id) : null;
    $units = [
      ['id' => 'title', 'source' => (string) $source->post_title, 'target' => $target instanceof \WP_Post ? (string) $target->post_title : ''],
    ];
    if ((string) $source->post_excerpt !== '') $units[] = ['id' => 'excerpt', 'source' => (string) $source->post_excerpt, 'target' => $target instanceof \WP_Post ? (string) $target->post_excerpt : ''];

    $extracted = AIContentSegments::extract((string) $source->post_content);
    if (is_wp_error($extracted)) return new \WP_Error('ymulti_xliff_segments', $extracted->get_error_message());
    $segments = isset($extracted['segments']) && is_array($extracted['segments']) ? $extracted['segments'] : [];
    $target_segments = [];
    if ($target instanceof \WP_Post) {
      $candidate = AIContentSegments::extract((string) $target->post_content);
      if (!is_wp_error($candidate) && isset($candidate['segments']) && is_array($candidate['segments']) && count($candidate['segments']) === count($segments)) {
        foreach ($candidate['segments'] as $segment) $target_segments[(string) ($segment['id'] ?? '')] = (string) ($segment['source'] ?? '');
      }
    }
    foreach ($segments as $segment) {
      $id = (string) ($segment['id'] ?? '');
      if ($id === '') continue;
      $units[] = ['id' => 'content:' . $id, 'source' => (string) ($segment['source'] ?? ''), 'target' => (string) ($target_segments[$id] ?? '')];
    }
    return $units;
  }

  /** @param array<int,array<string,string>> $units */
  private static function build_12(array $job, array $units, string $hash, string $source_locale, string $target_locale): string {
    $dom = new \DOMDocument('1.0', 'UTF-8');
    $dom->formatOutput = true;
    $root = $dom->createElementNS('urn:oasis:names:tc:xliff:document:1.2', 'xliff');
    $root->setAttribute('version', '1.2');
    $root->setAttributeNS('http://www.w3.org/2000/xmlns/', 'xmlns:ymulti', self::NS_META);
    self::set_meta_attributes($root, $job, $hash);
    $dom->appendChild($root);
    $file = $dom->createElementNS('urn:oasis:names:tc:xliff:document:1.2', 'file');
    $file->setAttribute('source-language', $source_locale);
    $file->setAttribute('target-language', $target_locale);
    $file->setAttribute('datatype', 'html');
    $file->setAttribute('original', 'post:' . (int) $job['source_post_id']);
    $root->appendChild($file);
    $body = $dom->createElementNS('urn:oasis:names:tc:xliff:document:1.2', 'body');
    $file->appendChild($body);
    foreach ($units as $unit) {
      $trans = $dom->createElementNS('urn:oasis:names:tc:xliff:document:1.2', 'trans-unit');
      $trans->setAttribute('id', $unit['id']);
      $source = $dom->createElementNS('urn:oasis:names:tc:xliff:document:1.2', 'source');
      $source->appendChild($dom->createCDATASection($unit['source']));
      $target = $dom->createElementNS('urn:oasis:names:tc:xliff:document:1.2', 'target');
      if ($unit['target'] !== '') $target->appendChild($dom->createCDATASection($unit['target']));
      $trans->appendChild($source);
      $trans->appendChild($target);
      $body->appendChild($trans);
    }
    return (string) $dom->saveXML();
  }

  /** @param array<int,array<string,string>> $units */
  private static function build_20(array $job, array $units, string $hash, string $source_locale, string $target_locale): string {
    $dom = new \DOMDocument('1.0', 'UTF-8');
    $dom->formatOutput = true;
    $root = $dom->createElementNS('urn:oasis:names:tc:xliff:document:2.0', 'xliff');
    $root->setAttribute('version', '2.0');
    $root->setAttribute('srcLang', $source_locale);
    $root->setAttribute('trgLang', $target_locale);
    $root->setAttributeNS('http://www.w3.org/2000/xmlns/', 'xmlns:ymulti', self::NS_META);
    self::set_meta_attributes($root, $job, $hash);
    $dom->appendChild($root);
    $file = $dom->createElementNS('urn:oasis:names:tc:xliff:document:2.0', 'file');
    $file->setAttribute('id', 'post-' . (int) $job['source_post_id']);
    $root->appendChild($file);
    foreach ($units as $unit) {
      $node = $dom->createElementNS('urn:oasis:names:tc:xliff:document:2.0', 'unit');
      $node->setAttribute('id', $unit['id']);
      $segment = $dom->createElementNS('urn:oasis:names:tc:xliff:document:2.0', 'segment');
      $source = $dom->createElementNS('urn:oasis:names:tc:xliff:document:2.0', 'source');
      $source->appendChild($dom->createCDATASection($unit['source']));
      $target = $dom->createElementNS('urn:oasis:names:tc:xliff:document:2.0', 'target');
      if ($unit['target'] !== '') $target->appendChild($dom->createCDATASection($unit['target']));
      $segment->appendChild($source);
      $segment->appendChild($target);
      $node->appendChild($segment);
      $file->appendChild($node);
    }
    return (string) $dom->saveXML();
  }

  private static function set_meta_attributes(\DOMElement $root, array $job, string $hash): void {
    $root->setAttributeNS(self::NS_META, 'ymulti:job-id', (string) (int) $job['id']);
    $root->setAttributeNS(self::NS_META, 'ymulti:source-id', (string) (int) $job['source_post_id']);
    $root->setAttributeNS(self::NS_META, 'ymulti:source-hash', $hash);
    $root->setAttributeNS(self::NS_META, 'ymulti:target-locale', (string) $job['target_locale']);
  }

  /** @return array<string,mixed>|\WP_Error */
  public static function parse_document(string $xml) {
    if (!self::available()) return new \WP_Error('ymulti_xliff_dom', __('XLIFF requires the PHP DOM extension.', 'yablonsky-multilingual'));
    if (strlen($xml) > self::MAX_FILE_BYTES) return new \WP_Error('ymulti_xliff_size', __('The XLIFF payload exceeds the 5 MB safety limit.', 'yablonsky-multilingual'));
    if (stripos($xml, '<!DOCTYPE') !== false || stripos($xml, '<!ENTITY') !== false) return new \WP_Error('ymulti_xliff_entities', __('Standard XML is accepted; DOCTYPE and entity declarations are rejected.', 'yablonsky-multilingual'));
    $previous = libxml_use_internal_errors(true);
    $dom = new \DOMDocument();
    $ok = $dom->loadXML($xml, LIBXML_NONET | LIBXML_NOBLANKS | LIBXML_NOERROR | LIBXML_NOWARNING);
    libxml_clear_errors();
    libxml_use_internal_errors($previous);
    if (!$ok || !$dom->documentElement || strtolower($dom->documentElement->localName) !== 'xliff') return new \WP_Error('ymulti_xliff_xml', __('Choose a valid XLIFF XML file for this import.', 'yablonsky-multilingual'));
    $root = $dom->documentElement;
    $version = (string) $root->getAttribute('version');
    if (!in_array($version, ['1.2', '2.0'], true)) return new \WP_Error('ymulti_xliff_version', __('Only XLIFF 1.2 and 2.0 are supported.', 'yablonsky-multilingual'));
    $job_id = absint($root->getAttributeNS(self::NS_META, 'job-id'));
    $source_hash = sanitize_text_field($root->getAttributeNS(self::NS_META, 'source-hash'));
    $target_locale = sanitize_text_field($root->getAttributeNS(self::NS_META, 'target-locale'));
    if ($job_id <= 0 || strlen($source_hash) !== 64 || $target_locale === '') return new \WP_Error('ymulti_xliff_meta', __('The XLIFF file is missing the YMulti job identity or source snapshot. Export a fresh package from this job, then import that package.', 'yablonsky-multilingual'));

    $xpath = new \DOMXPath($dom);
    $units = [];
    if ($version === '1.2') {
      $nodes = $xpath->query('//*[local-name()="trans-unit"]');
      if ($nodes) foreach ($nodes as $node) {
        if (!$node instanceof \DOMElement) continue;
        $id = sanitize_text_field($node->getAttribute('id'));
        $targets = $xpath->query('./*[local-name()="target"]', $node);
        $target = $targets && $targets->length > 0 ? trim((string) $targets->item(0)->textContent) : '';
        if ($id !== '') $units[$id] = $target;
      }
    } else {
      $nodes = $xpath->query('//*[local-name()="unit"]');
      if ($nodes) foreach ($nodes as $node) {
        if (!$node instanceof \DOMElement) continue;
        $id = sanitize_text_field($node->getAttribute('id'));
        $targets = $xpath->query('./*[local-name()="segment"]/*[local-name()="target"]', $node);
        $target = $targets && $targets->length > 0 ? trim((string) $targets->item(0)->textContent) : '';
        if ($id !== '') $units[$id] = $target;
      }
    }
    if (!$units || empty($units['title'])) return new \WP_Error('ymulti_xliff_targets', __('The XLIFF file must contain a translated title and every required content segment. Complete those units, then import the package again.', 'yablonsky-multilingual'));
    return ['version' => $version, 'job_id' => $job_id, 'source_hash' => $source_hash, 'target_locale' => $target_locale, 'units' => $units];
  }

  /** @return int|\WP_Error */
  private static function apply_import(array $job, array $parsed) {
    $source_id = absint($job['source_post_id'] ?? 0);
    $source = get_post($source_id);
    if (!$source instanceof \WP_Post) return new \WP_Error('ymulti_xliff_source', __('Choose an existing source post for this translation job.', 'yablonsky-multilingual'));
    // Validate the complete imported content BEFORE creating or changing any
    // target draft. A rejected XLIFF must not leave behind a new draft.
    $units = isset($parsed['units']) && is_array($parsed['units']) ? $parsed['units'] : [];

    $extracted = AIContentSegments::extract((string) $source->post_content);
    if (is_wp_error($extracted)) return $extracted;
    $segments = isset($extracted['segments']) && is_array($extracted['segments']) ? $extracted['segments'] : [];
    $translations = [];
    foreach ($segments as $segment) {
      $id = (string) ($segment['id'] ?? '');
      if ($id === '') continue;
      $key = 'content:' . $id;
      $value = isset($units[$key]) ? trim((string) $units[$key]) : '';
      if ($value === '') return new \WP_Error('ymulti_xliff_missing_segment', sprintf(
        /* translators: %s: XLIFF content segment identifier. */
        __('The XLIFF file is missing a translation for required content segment %s. Complete that unit, then import the package again.', 'yablonsky-multilingual'),
        $id
      ));
      $translations[$id] = $value;
    }
    $content = (string) $source->post_content;
    if ($segments) {
      $content_result = AIContentSegments::apply((string) $source->post_content, $segments, $translations);
      if (is_wp_error($content_result)) return $content_result;
      $content = (string) $content_result;
    }
    $excerpt = (string) $source->post_excerpt;
    if ((string) $source->post_excerpt !== '') {
      $translated_excerpt = trim((string) ($units['excerpt'] ?? ''));
      if ($translated_excerpt === '') return new \WP_Error('ymulti_xliff_excerpt', __('The translated excerpt is missing from the XLIFF file. Complete the excerpt unit, then import the package again.', 'yablonsky-multilingual'));
      $excerpt = $translated_excerpt;
    }
    $title = trim((string) ($units['title'] ?? ''));
    if ($title === '') return new \WP_Error('ymulti_xliff_title', __('The XLIFF file must contain a translated title and every required content segment. Complete those units, then import the package again.', 'yablonsky-multilingual'));
    $target_id = TranslationJobs::ensure_target_draft($job, get_current_user_id());
    if (is_wp_error($target_id)) return $target_id;
    $target_post = get_post((int) $target_id);
    // A job may point at an existing public translation. Never silently
    // replace or unpublish that live resource with an imported review draft.
    if (!($target_post instanceof \WP_Post) || !in_array((string) $target_post->post_status, ['draft', 'pending', 'auto-draft'], true)) {
      return new \WP_Error('ymulti_xliff_review_draft_only', __('Target translation draft is unavailable. Start the job to create its target draft, then complete the review.', 'yablonsky-multilingual'));
    }
    $updated = wp_update_post([
      'ID' => (int) $target_id,
      'post_title' => sanitize_text_field($title),
      'post_excerpt' => wp_kses_post($excerpt),
      'post_content' => $content,
      // Keep a pre-existing editorial review status instead of silently
      // demoting pending submissions to a normal draft on import.
      'post_status' => (string) $target_post->post_status === 'pending' ? 'pending' : 'draft',
    ], true);
    if (is_wp_error($updated)) return $updated;
    return (int) $updated;
  }

  private static function redirect_notice(string $type, string $message): void {
    set_transient('ymulti_translation_job_notice_' . get_current_user_id(), ['type' => $type, 'message' => sanitize_text_field($message)], 60);
    wp_safe_redirect(admin_url('admin.php?page=ypm-translation-jobs'));
    exit;
  }
}
